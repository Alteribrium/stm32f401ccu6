#include "PA7.h"

static volatile uint8_t table_running = 0;
static uint16_t current_period = 100; // ?? 20 ?? 10000

void Table_Init(void) {
    // 1. ????????? ????????????
    RCC->AHB1ENR |= RCC_AHB1ENR_GPIOAEN;
    RCC->APB1ENR |= RCC_APB1ENR_TIM3EN;
    
    // 2. ????????? PA7 ??? Alternate Function
    GPIOA->MODER &= ~GPIO_MODER_MODER7;
    GPIOA->MODER |= GPIO_MODER_MODER7_1; // Alternate Function mode
    
    // 3. ????????? AF2 ??? PA7 (TIM3_CH2)
    GPIOA->AFR[0] &= ~(0xF << 28);     // ????? ????? 28-31 (PA7)
    GPIOA->AFR[0] |= (2 << 28);        // AF2 ??? TIM3_CH2
    
    // 4. ????????? ???????? ??????
    GPIOA->OSPEEDR |= (3 << 14);       // High speed ??? PA7 (???? 14-15)
    
    // 5. ????????? TIM3 ??? ??? ?? ?????? 2
    TIM3->PSC = 16 - 1;                // ????????????
    TIM3->ARR = current_period;        // ??????
    TIM3->CCR2 = 0;//current_period / 2;   // 50% ?????????? ??? ?????? 2
    
    // 6. ????????? ?????? ??? ??? ?????? 2
    TIM3->CCMR1 &= ~TIM_CCMR1_OC2M;    // ????? ????? ?????? ??? ?????? 2
    TIM3->CCMR1 |= TIM_CCMR1_OC2M_1 | TIM_CCMR1_OC2M_2; // PWM mode 1 (110)
    TIM3->CCMR1 |= TIM_CCMR1_OC2PE;    // ???????? ???????????? ??? ?????? 2
    
    // 7. ????????? ?????? ?????? 2
    TIM3->CCER |= TIM_CCER_CC2E;
    
    // 8. ?????? ???? ?? ???????
		TIM3->CR1 |= TIM_CR1_CEN;
		Stop_Table();
}

void Start_Table(void) {
    if (!table_running) {
        table_running = 1;
				TIM3->CNT = 1;
        TIM3->CCR2 = current_period / 2;
				TIM3->CR1 |= TIM_CR1_CEN;
    }
}

void Stop_Table(void) {
    if (table_running) {
        table_running = 0; 
        TIM3->CCR2 = 0;
    }
}
