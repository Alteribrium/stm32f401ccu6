#include "PB0.h"

static volatile uint8_t table_running = 0;
static uint16_t current_period = 700; // ?? 20 ?? 10000

void Dispenser_B0_Init(void) {
    // 1. ????????? ????????????
    RCC->AHB1ENR |= RCC_AHB1ENR_GPIOBEN;
    RCC->APB1ENR |= RCC_APB1ENR_TIM3EN;
    
    // 2. ????????? PB0 ??? Alternate Function
    GPIOB->MODER &= ~GPIO_MODER_MODER0;
    GPIOB->MODER |= GPIO_MODER_MODER0_1; // Alternate Function mode
    
    // 3. ????????? AF2 ??? PB0 (TIM3_CH3)
    GPIOB->AFR[0] &= ~(0xF << 0);        // ????? ????? 0-3 (PB0)
    GPIOB->AFR[0] |= (2 << 0);           // AF2 ??? TIM3_CH3
    
    // 4. ????????? ???????? ??????
    GPIOB->OSPEEDR |= (3 << 0);          // High speed ??? PB0 (???? 0-1)
    
    // 5. ????????? TIM3 ??? ??? ?? ?????? 3
    TIM3->PSC = 16 - 1;                  // ????????????
    TIM3->ARR = current_period;          // ??????
    TIM3->CCR3 = 0;                      // ?????????? ????????
    
    // 6. ????????? ?????? ??? ??? ?????? 3
    TIM3->CCMR2 &= ~TIM_CCMR2_OC3M;      // ????? ????? ??????
    TIM3->CCMR2 |= TIM_CCMR2_OC3M_1 | TIM_CCMR2_OC3M_2; // PWM mode 1
    TIM3->CCMR2 |= TIM_CCMR2_OC3PE;      // ???????? ????????????
    
    // 7. ????????? ?????? ?????? 3
    TIM3->CCER |= TIM_CCER_CC3E;
    
    // 8. ?????? ???? ?? ???????
    TIM3->CR1 |= TIM_CR1_CEN;
    Stop_Dispenser_B0();
}

void Start_Dispenser_B0(void) {
    if (!table_running) {
        table_running = 1;
        TIM3->CNT = 1;
        TIM3->CCR3 = current_period / 2;
        TIM3->CR1 |= TIM_CR1_CEN;
    }
}

void Stop_Dispenser_B0(void) {
    if (table_running) {
        table_running = 0;
        TIM3->CCR3 = 0;
    }
}
