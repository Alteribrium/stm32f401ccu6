#include "PB1.h"

static volatile uint8_t table_running = 0;
static uint16_t current_period = 700; // ?? 20 ?? 10000

void Table_Init(void) {
    // 1. ????????? ????????????
    RCC->AHB1ENR |= RCC_AHB1ENR_GPIOBEN;
    RCC->APB1ENR |= RCC_APB1ENR_TIM3EN;
    
    // 2. ????????? PB1 ??? Alternate Function
    GPIOB->MODER &= ~GPIO_MODER_MODER1;
    GPIOB->MODER |= GPIO_MODER_MODER1_1; // Alternate Function mode
    
    // 3. ????????? AF2 ??? PB1 (TIM3_CH4)
    GPIOB->AFR[0] &= ~(0xF << 4);        // ????? ????? 4-7 (PB1)
    GPIOB->AFR[0] |= (2 << 4);           // AF2 ??? TIM3_CH4
    
    // 4. ????????? ???????? ??????
    GPIOB->OSPEEDR |= (3 << 2);          // High speed ??? PB1 (???? 2-3)
    
    // 5. ????????? TIM3 ??? ??? ?? ?????? 4
    TIM3->PSC = 16 - 1;                  // ????????????
    TIM3->ARR = current_period;          // ??????
    TIM3->CCR4 = 0;                      // ?????????? ????????
    
    // 6. ????????? ?????? ??? ??? ?????? 4
    TIM3->CCMR2 &= ~TIM_CCMR2_OC4M;      // ????? ????? ??????
    TIM3->CCMR2 |= TIM_CCMR2_OC4M_1 | TIM_CCMR2_OC4M_2; // PWM mode 1
    TIM3->CCMR2 |= TIM_CCMR2_OC4PE;      // ???????? ????????????
    
    // 7. ????????? ?????? ?????? 4
    TIM3->CCER |= TIM_CCER_CC4E;
    
    // 8. ?????? ???? ?? ???????
    TIM3->CR1 |= TIM_CR1_CEN;
    Stop_Table();
}

void Start_Table(void) {
    if (!table_running) {
        table_running = 1;
        TIM3->CNT = 1;
        TIM3->CCR4 = current_period / 2;
        TIM3->CR1 |= TIM_CR1_CEN;
    }
}

void Stop_Table(void) {
    if (table_running) {
        table_running = 0;
        TIM3->CCR4 = 0;
    }
}
